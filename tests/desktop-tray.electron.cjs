const { app, BrowserWindow, WebContentsView, dialog } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { installWindowLifecycle } = require('../desktop/window-lifecycle.cjs');
const { installDesktopTray } = require('../desktop/tray.cjs');

app.setPath('userData', fs.mkdtempSync(path.join(os.tmpdir(), 'xiaomei-tray-test-')));
app.on('window-all-closed', () => {});
const watchdog = setTimeout(() => { console.error('Tray test timed out'); app.exit(1); }, 15000);
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));

app.whenReady().then(async () => {
  const window = new BrowserWindow({ width: 600, height: 400, show: false, webPreferences: { backgroundThrottling: false } });
  const product = new WebContentsView({ webPreferences: { backgroundThrottling: false } });
  window.contentView.addChildView(product);
  let cleaned = 0;
  const lifecycle = installWindowLifecycle(window, () => { cleaned++; product.webContents.close(); });
  const control = installDesktopTray(window, lifecycle, path.join(__dirname, '../static/images/app-icon.ico'), '小美画布测试');
  await window.loadURL('data:text/html,<input id="draft" value="saved draft"><script>window.ticks=0;setInterval(()=>window.ticks++,50)</script>');
  await product.webContents.loadURL('data:text/html,<p>Product view</p>');
  control.show();
  await delay(100);
  const before = await window.webContents.executeJavaScript('window.ticks');
  assert.equal(control.hide().ok, true);
  lifecycle.schedule(() => { if (!control.isHidden()) window.show(); }, 100);
  await delay(350);
  assert.equal(window.isVisible(), false);
  assert.equal(window.isDestroyed(), false);
  assert.equal(product.webContents.isDestroyed(), false);
  assert.equal(cleaned, 0);
  assert.ok(await window.webContents.executeJavaScript('window.ticks') > before, 'background timers continue');
  control.show();
  assert.equal(window.isVisible(), true);
  assert.equal(await window.webContents.executeJavaScript('document.getElementById("draft").value'), 'saved draft');
  window.minimize();
  control.hide();
  control.show();
  assert.equal(window.isMinimized(), false);
  let prompts = 0;
  let finalQuit = false;
  app.once('will-quit', () => { finalQuit = true; });
  dialog.showMessageBox = async () => { prompts++; return { response: 0 }; };
  await window.webContents.executeJavaScript('window.onbeforeunload = e => { e.returnValue = false; }; void 0;');
  app.quit();
  await delay(250);
  assert.equal(prompts, 1);
  assert.equal(window.isDestroyed(), false);
  assert.equal(finalQuit, false, 'canceled exit never reaches service cleanup');
  assert.equal(control.hide().ok, true, 'tray remains usable after canceled exit');
  control.show();
  await window.webContents.executeJavaScript('window.onbeforeunload = null; void 0;');
  window.close();
  await delay(250);
  assert.equal(window.isDestroyed(), true);
  assert.equal(cleaned, 1);
  clearTimeout(watchdog);
  console.log('PASS: native tray creation, hide, background timers, retained views and draft, restore, minimize, canceled exit, normal close');
  app.exit(0);
}).catch(error => { console.error(error); app.exit(1); });
