const {app, BrowserWindow} = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const profile = fs.mkdtempSync(path.join(os.tmpdir(),'xiaomei-image-space-ui-'));
app.setPath('userData',profile);
app.disableHardwareAcceleration();
const watchdog = setTimeout(() => { console.error('UI test timeout'); app.exit(1); }, 60000);
app.whenReady().then(async () => {
  const win = new BrowserWindow({show:false,width:1500,height:960,webPreferences:{contextIsolation:true,nodeIntegration:false,offscreen:true,backgroundThrottling:false}});
  const errors=[];
  win.webContents.on('console-message',(_e,level,message)=>{ if(level>=3 && !message.includes('404')) errors.push(message); });
  const run = code => win.webContents.executeJavaScript(code,true).catch(error => { console.error('Failed script:',code,errors); throw error; });
  const waitFor = async code => {for(let i=0;i<100;i++){if(await run(`Boolean(${code})`))return;await new Promise(r=>setTimeout(r,100));}throw new Error('Timeout: '+code);};
  await win.loadURL('http://127.0.0.1:3017/static/asset-manager.html');
  await waitFor("document.querySelector('[data-space-toggle]') && localAssetsLoaded");
  assert.equal(await run('currentAssetItems().length'),4);
  await run("document.querySelector('[data-space-toggle]').click()");
  await waitFor("document.querySelector('[data-space-form]')");
  await run("document.querySelector('[data-space-filter=\"color\"]').value='金色'; document.querySelector('[data-space-filter=\"shape\"]').value='portrait'; document.querySelector('[data-space-form]').requestSubmit()");
  await waitFor('currentAssetItems().length === 1');
  assert.equal(await run('currentAssetItems()[0].id'),'asset_24');
  await run("document.querySelector('[data-space-save]').click()");
  await waitFor("document.querySelector('dialog[open] input[name=collectionName]')");
  await run("document.querySelector('input[name=collectionName]').value='金色竖版相框'; document.querySelector('dialog[open] form').requestSubmit(document.querySelector('dialog[open] button[value=save]'))");
  await waitFor('imageSpaceState.collections.length === 1');
  await run("document.querySelector('[data-space-clear]').click()");
  await waitFor('currentAssetItems().length === 4');
  await run("document.querySelector('[data-space-collection]').click()");
  await waitFor('currentAssetItems().length === 1');
  await run("document.querySelector('[data-space-edit]').click()");
  await waitFor("document.querySelector('#imageSpaceEditor[open]')");
  await run("document.querySelector('#imageSpaceEditor input[name=tags]').value='精选,主图'; document.querySelector('[data-space-editor-save]').click()");
  await waitFor("!document.querySelector('#imageSpaceEditor')");
  assert.deepEqual(await run('currentAssetItems()[0].classification.tags'),['精选','主图']);
  const output=path.join(os.tmpdir(),'xiaomei-image-space-ui.png');
  await run("Promise.all([...document.querySelectorAll('img')].map(img => img.decode().catch(()=>{}))).then(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))");
  fs.writeFileSync(output,(await win.webContents.capturePage()).toPNG());
  win.reload();
  await waitFor("document.querySelector('[data-space-collection]') && localAssetsLoaded");
  await run("document.querySelector('[data-space-collection]').click()");
  await waitFor('currentAssetItems().length === 1');
  assert.deepEqual(await run('currentAssetItems()[0].classification.tags'),['精选','主图']);
  await run("document.querySelector('[data-space-toggle]').click()");
  await waitFor("document.querySelector('[data-space-form]')");
  // Update from an edited filter form without pressing Apply first.
  await run("document.querySelector('[data-space-filter=\"color\"]').value='白色'; document.querySelector('[data-space-filter=\"shape\"]').value='landscape'; document.querySelector('[data-space-update]').click()");
  await waitFor("document.querySelector('dialog[open] input[name=collectionName]')");
  await run("document.querySelector('input[name=collectionName]').value='白色横版相框'; document.querySelector('dialog[open] form').requestSubmit(document.querySelector('dialog[open] button[value=save]'))");
  await waitFor("currentAssetItems().length === 3 && imageSpaceState.collections[0].filters.color === '白色'");
  assert.equal(await run("imageSpaceState.collections[0].filters.color"),'白色');
  await run("window.confirm=()=>true; document.querySelector('[data-space-delete]').click()");
  await waitFor('imageSpaceState.collections.length === 0');
  await run("document.querySelector('[data-space-clear]').click()");
  await run("activeTab='local'; imageSpaceState.collectionId=''; render(); document.querySelector('[data-space-edit]').click()");
  await waitFor("document.querySelector('#imageSpaceEditor[open]')");
  await run("document.querySelector('#imageSpaceEditor input[name=tags]').value='本地精选'; document.querySelector('[data-space-editor-save]').click()");
  await waitFor("!document.querySelector('#imageSpaceEditor')");
  assert.deepEqual(await run('localUploadItems()[0].classification.tags'),['本地精选']);
  await run("activeTab='generated'; imageSpaceState.collectionId=''; render(); loadGeneratedAssets()");
  await waitFor('generatedAssetsState.loaded && !generatedAssetsState.loading');
  assert.equal(await run('generatedAssetsState.total'),25);
  await run("imageSpaceState.filters.generated={color:'金色',shape:'portrait'}; loadGeneratedAssets()");
  await waitFor('!generatedAssetsState.loading && generatedAssetsState.total === 1');
  assert.equal(await run('generatedAssetItems()[0].name'),'相框24.png');
  await run("document.querySelector('[data-space-edit]').click()");
  await waitFor("document.querySelector('#imageSpaceEditor[open]')");
  await run("document.querySelector('#imageSpaceEditor input[name=tags]').value='生成精选'; document.querySelector('[data-space-editor-save]').click()");
  await waitFor("!document.querySelector('#imageSpaceEditor') && !generatedAssetsState.loading");
  assert.deepEqual(await run('generatedAssetItems()[0].classification.tags'),['生成精选']);
  await run("document.querySelector('[data-space-edit]').click()");
  await waitFor("document.querySelector('#imageSpaceEditor[open]')");
  await run("document.documentElement.classList.add('studio-theme-dark'); document.body.classList.add('theme-dark'); new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))");
  const dark=path.join(os.tmpdir(),'xiaomei-image-space-editor-dark.png');
  fs.writeFileSync(dark,(await win.webContents.capturePage()).toPNG());
  assert.equal(await run("document.querySelector('#imageSpaceEditor').getBoundingClientRect().bottom <= window.innerHeight"),true);
  await run("document.querySelector('#imageSpaceEditor input[name=tags]').value='x'.repeat(25); document.querySelector('[data-space-editor-save]').click()");
  await waitFor("document.querySelector('#imageSpaceEditor [role=alert]').textContent.includes('24')");
  await run("document.querySelector('[data-space-editor-reset]').click()");
  await waitFor("!document.querySelector('#imageSpaceEditor') && !generatedAssetsState.loading");
  assert.deepEqual(await run('generatedAssetItems()[0].classification.tags'),['参考图']);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({ok:true,screenshot:output,darkScreenshot:dark,checks:['combination','collections save/reopen/reload/update/delete','manual edit uploaded/local/generated/reset/validation','pagination filtering','dark editor layout']}));
  clearTimeout(watchdog);
  win.destroy();app.quit();
}).catch(error=>{console.error(error);app.exit(1);});
